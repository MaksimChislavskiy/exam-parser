def build_task_extraction_prompt(markdown: str, image_ids: list[str]) -> str:
    candidates = "\n".join(f"- {image_id}" for image_id in image_ids) or "- нет"
    return f"""
Извлеки математические задачи из OCR Markdown.

Правила:
1. Markdown — источник содержания задачи. Не изменяй числа, переменные, формулы,
   номера задач, буквы точек и названия углов. Разрешено исправить только явную
   OCR-опечатку в обычном русском слове, когда правильный вариант однозначен.
2. Никогда не переставляй и не заменяй буквы в геометрических обозначениях:
   $ACB$ нельзя превращать в $ABC$, а $APQ$ — в $APO$.
3. Игнорируй заголовки, общие инструкции, строки ответа, колонтитулы, справочные
   материалы и страницы/таблицы с готовыми ответами. Верни задачи в порядке чтения.
4. Объедини все подпункты одной нумерованной задачи в поле condition.
5. Сохрани существующий LaTeX. Все остальные математические фрагменты,
   геометрические обозначения и имена вершин оберни в $...$.
   Примеры: A1 -> $A_1$, CC1 -> $CC_1$,
   A2BB2 -> $A_2BB_2$, ABCDA1B1C1D1 -> $ABCDA_1B_1C_1D_1$.
6. Для картинки верни точное имя файла в image_id только тогда, когда тег
   изображения находится после начала этой задачи и до начала следующей задачи.
7. Не привязывай к задаче логотипы, значки предупреждений, декоративные элементы,
   номера страниц и изображения после последней задачи, не являющиеся частью её
   условия. Если принадлежность изображения неочевидна, верни null.
8. Не решай задачи и не придумывай отсутствующий текст.
9. Если на странице нет условий задач, верни пустой список tasks.
10. Маркер {OCR_UNREADABLE_REPEAT_MARKER} означает доказанный нечитаемый
   OCR-фрагмент. Сохрани маркер дословно и не восстанавливай пропущенное по
   догадке.

Файлы изображений:
{candidates}

Markdown:
{markdown}
""".strip()


def build_angle_notation_check_prompt(marked_condition: str) -> str:
    return f"""
Отдельно проверь одно подозрительное геометрическое обозначение в OCR-условии.
Проверяемое место заключено в теги <angle_to_check>...</angle_to_check>.

Правила:
1. Анализируй всё условие, взаимное расположение названных точек и математический
   смысл утверждения. Угол, обозначенный тремя буквами, имеет вершину на втором
   месте.
2. Если в отмеченном двухбуквенном обозначении OCR пропустил ровно одну букву и
   полное трёхбуквенное обозначение однозначно восстанавливается из условия,
   верни его в corrected_notation.
3. Если точную пропущенную букву или её позицию нельзя установить однозначно,
   верни corrected_notation=null. Не угадывай по наиболее частому шаблону.
4. Не исправляй другие буквы, числа, слова или формулы и не решай задачу.
5. Верни только само обозначение без знака угла и без LaTeX-разделителей.

OCR-условие:
{marked_condition}
""".strip()


def build_document_answers_prompt(markdown: str) -> str:
    return f"""
Извлеки только готовые ответы из раздела, страницы или таблицы ответов в OCR Markdown.

Правила:
1. Ответы должны быть явно написаны в документе. Никогда не решай задачи сам.
2. Для каждого номера задания верни одну запись task_num + answer.
3. Для заданий с подпунктами сохрани все подпункты одного задания в одном поле
   answer, включая обозначения «а)», «б)», «в)» и математические интервалы.
4. Сохрани точные числа, знаки, дроби и существующий LaTeX. Не сокращай ответ.
5. Игнорируй пустые строки «Ответ: ____» внутри самих заданий.
6. Если явного раздела с ответами нет, верни пустой список answers.

Markdown всех страниц документа:
{markdown}
""".strip()
